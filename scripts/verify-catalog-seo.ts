import assert from 'node:assert/strict';
import { catalogMetadata, isIndexableProduct, productMetadata, productStructuredData, kitStructuredData } from '../src/lib/catalog-seo';
import { productSeoDescription } from '../src/lib/page-seo';
import { searchMetadata } from '../src/lib/search-seo';
import { publicStoreProduct } from '../src/lib/public-store-presentation';
import { serializeJsonLd } from '../src/lib/seo';
import type { Product, Kit } from '../src/lib/types';
import { collectSitemapRows } from '../src/lib/sitemap-pagination';

const store = { nome_loja: 'Minha loja', slug: 'minha-loja' };
const product = { id: '123', store_id: 'store', titulo: 'Jogo de leitura', slug: 'jogo-de-leitura', preco: 12.5, preco_plr: 30, is_plr: true, is_free: false, tipo: 'pdf', status: 'publicado', created_at: '2026-01-01', descricao: '<p>Atividades de leitura e escrita para trabalhar com a turma.</p>', arquivo_url: 'PRIVATE', plr_license_url: 'PRIVATE', capa_url: 'https://example.com/capa.jpg', page_count: 10, age_range: '6 a 8 anos', review_count: 0, average_rating: 0 } as Product;
assert(isIndexableProduct(product));
assert(!isIndexableProduct({ ...product, status: 'rascunho' }));
assert(!isIndexableProduct({ ...product, excluido_em: '2026-10-12' }));
const standard = productStructuredData(product, store);
assert.equal(standard.offers?.price, '12.50');
assert.equal(standard.offers?.seller.name, store.nome_loja);
assert.equal(standard.brand.name, store.nome_loja);
assert.equal(productMetadata(product).alternates?.canonical, productMetadata(product, true).alternates?.canonical);
assert.equal(productMetadata(product).robots && typeof productMetadata(product).robots === 'object' ? (productMetadata(product).robots as { index: boolean }).index : false, true);
assert.equal(productMetadata({ ...product, plr_descricao: 'Termos reais da licença de revenda.' }, true).description, 'Jogo de leitura. Termos reais da licença de revenda.');
assert.equal(productSeoDescription('Título', '<script>nao incluir</script><p>Texto real &quot;curto&quot;.</p>'), 'Texto real "curto".');
assert.equal(productStructuredData({ ...product, descricao: 'Conteúdo completo. '.repeat(30) }, store).description.length > 160, true);
assert.notEqual(productStructuredData(product, store, true)['@id'], standard['@id']);
assert.equal(productStructuredData(product, store, true).offers?.price, '30.00');
assert.match(productStructuredData(product, store, true).offers?.url || '', /\?licenca=plr$/);
assert.equal(productStructuredData({ ...product, is_free: true }, store).offers?.price, '0.00');
assert.equal(productStructuredData({ ...product, preco: NaN }, store).offers, undefined);
assert.equal(standard.aggregateRating, undefined);
assert.equal(productMetadata(product, false, store).alternates?.canonical, productMetadata(product).alternates?.canonical);
assert.equal(productStructuredData(product, store, false, undefined, true).url, standard.url);
assert.equal(productStructuredData({ ...product, review_count: 2, average_rating: 4.5 }, store).aggregateRating?.reviewCount, 2);
assert.equal(productStructuredData({ ...product, review_count: 2, average_rating: 7 }, store).aggregateRating, undefined);
assert.equal(catalogMetadata(product.titulo, product.descricao, '/produto/jogo-de-leitura').alternates?.canonical, 'https://www.educalizando.com.br/produto/jogo-de-leitura');
assert.equal(kitStructuredData({ id: 'kit', titulo: 'Combo', descricao: null, preco_kit: 10 } as Kit, store, '/kit/kit').offers?.price, '10.00');
const presentation = publicStoreProduct(product);
assert.equal(presentation.arquivo_url, null);
assert.equal(presentation.plr_license_url, undefined);
assert.equal(presentation.descricao, product.descricao);
assert.equal(presentation.preco_plr, product.preco_plr);
assert(!serializeJsonLd({ name: '</script><img>' }).includes('<'));
assert.deepEqual(searchMetadata({ q: 'leitura' }).robots, { index: false, follow: true });
assert.deepEqual(searchMetadata({ categoria: 'alfabetizacao', sort: 'popular' }).robots, { index: false, follow: true });
assert.deepEqual(searchMetadata({ categoria: 'desconhecida' }).robots, { index: false, follow: true });
assert.equal(searchMetadata({ categoria: 'alfabetizacao', page: '2' }).alternates?.canonical, 'https://www.educalizando.com.br/buscar?categoria=alfabetizacao&page=2');
assert.equal(searchMetadata({ utm_source: 'whatsapp' }).alternates?.canonical, 'https://www.educalizando.com.br/buscar');
console.log('PASS SEO: preços final/PLR/grátis, vendedor, canonicals, avaliações reais, páginas públicas, filtros e privacidade das vitrines.');
async function verifySitemap() {
  const offsets: number[] = [];
  const rows = await collectSitemapRows(async (from, to) => {
    offsets.push(from);
    assert.equal(to, from + 999);
    return { data: Array.from({ length: from === 0 ? 1000 : 1 }, (_, i) => ({ id: from + i })), error: null };
  });
  assert.equal(rows.length, 1001);
  assert.deepEqual(offsets, [0, 1000]);
  await assert.rejects(collectSitemapRows(async () => ({ data: null, error: new Error('Database unavailable') })), /Database unavailable/);
  await assert.rejects(collectSitemapRows(async () => ({ data: Array.from({ length: 1000 }, (_, i) => i), error: null })), /múltiplos sitemaps/);
  console.log('PASS sitemap: paginação além de 1.000 linhas, erros explícitos e proteção contra corte silencioso.');
}
void verifySitemap().catch(error => { console.error(error); process.exitCode = 1; });
